// Regenerates the release notes from git history: one RELEASES.md per plugin and
// one matrix at the repo root.
//
//   node tools/gen-releases.js            rewrite the files
//   node tools/gen-releases.js --check    exit 1 if a release in git is missing
//                                         from them (what the Stop hook runs)
//
// Nothing here is hand-maintained. A release *is* a commit that moved a plugin's
// `version:`, and the note *is* that commit's subject - both already written, and
// both already reviewed. A hand-kept changelog beside them would be a third copy
// free to disagree with the two that are load-bearing.
//
// One consequence to know: a release row names the commit that bumped the
// version, so it cannot be written *by* that commit - adding the row would change
// the sha the row points at. The files therefore land in the following commit,
// which is what the hook asks for.
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const REPO = path.join(__dirname, '..');
const git = (...args) =>
  execFileSync('git', args,
    // stderr to /dev/null: `git show <sha>:<path>` is used as a probe for "did this
    // file exist at that commit", and its complaint when it did not is the answer,
    // not a failure worth printing 200 times.
    { cwd: REPO, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] });

const PLUGINS = fs.readdirSync(REPO)
  .filter((d) => fs.existsSync(path.join(REPO, d, d + '.yml')))
  .sort();

// Short column headings, because five full plugin names make a table nothing can
// read. The legend above the table is what maps them back.
const SHORT = {
  NormalizeParentTags: 'NPT',
  MergePerformerTagsToScenes: 'MPTTS',
  PropagateTagsAndPerformers: 'PTP2RE',
  CustomFieldsBulkEditor: 'CFBE',
  TagBundleClipboard: 'TBC',
  EntityNameMaintainer: 'ENM',
  FindEntitiesByTextContent: 'FETC',
};
const short = (p) => SHORT[p] || p;

const repoUrl = (() => {
  try {
    return git('remote', 'get-url', 'origin').trim().replace(/\.git$/, '');
  } catch (e) { return null; }
})();

// Which commits the remote has. A cell can only carry a link to something a
// reader can open, so an unpushed release shows its short id instead.
const pushed = (() => {
  const set = new Set();
  try {
    git('rev-list', 'origin/HEAD').split('\n').forEach((s) => s && set.add(s));
  } catch (e) {
    try { git('rev-list', 'origin/main').split('\n').forEach((s) => s && set.add(s)); }
    catch (e2) { /* no remote-tracking branch: everything reads as unpushed */ }
  }
  return set;
})();

const versionAt = (sha, file) => {
  try {
    const m = /^version:\s*(\S+)\s*$/m.exec(git('show', sha + ':' + file));
    return m ? m[1] : null;
  } catch (e) { return null; }   // the file did not exist at that commit
};

// Every commit that touched a plugin's manifest or its yml, oldest first, with
// the version each one left behind. Both files, because the manifest arrived
// after the yml in at least one plugin and the early releases are only in the yml.
function releasesFor(plugin) {
  const files = [plugin + '/manifest', plugin + '/' + plugin + '.yml'];
  const log = git('log', '--reverse', '--format=%H\x1f%aI\x1f%s', '--', ...files);
  const out = [];
  let previous = null;
  log.split('\n').filter(Boolean).forEach((line) => {
    const [sha, iso, subject] = line.split('\x1f');
    const v = versionAt(sha, files[0]) || versionAt(sha, files[1]);
    if (!v || v === previous) return;
    out.push({ plugin, version: v, sha, date: iso.slice(0, 10), subject });
    previous = v;
  });
  return out.reverse();          // newest first, everywhere
}

// The short id in both branches: GitHub resolves it, and a full 40-character sha
// in every cell makes the raw table unreadable in the editor it is written in.
const cell = (r) => {
  const id = r.sha.slice(0, 7);
  if (repoUrl && pushed.has(r.sha)) return '[' + r.version + '](' + repoUrl + '/commit/' + id + ')';
  return r.version + ' (`' + id + '`)';
};

const HEAD = '<!-- Generated by tools/gen-releases.js from git history. Do not edit by hand. -->\n';

function pluginFile(plugin, releases) {
  const rows = releases.map((r) =>
    '| ' + cell(r) + ' | ' + r.date + ' | ' + r.subject.replace(/\|/g, '\\|') + ' |');
  return HEAD +
    '\n# ' + plugin + ' — releases\n\n' +
    'Newest first. Each version links to the commit that shipped it; the note is that commit\'s\n' +
    'own subject. The reasoning behind a release is in `CLAUDE.md`, and what the plugin does now\n' +
    'is in `README.md` — neither of those carries version history.\n\n' +
    '| Version | Date | Change |\n| --- | --- | --- |\n' + rows.join('\n') + '\n';
}

function rootFile(all) {
  const byCommit = new Map();
  all.forEach((r) => {
    if (!byCommit.has(r.sha)) byCommit.set(r.sha, { date: r.date, sha: r.sha, subject: r.subject, cells: {} });
    byCommit.get(r.sha).cells[r.plugin] = r;
  });
  const order = git('log', '--format=%H').split('\n').filter(Boolean);   // newest first
  const rows = order.filter((sha) => byCommit.has(sha)).map((sha) => {
    const c = byCommit.get(sha);
    return '| ' + c.date + ' | ' +
      PLUGINS.map((p) => (c.cells[p] ? cell(c.cells[p]) : '')).join(' | ') +
      ' | ' + c.subject.replace(/\|/g, '\\|') + ' |';
  });
  return HEAD +
    '\n# Releases\n\n' +
    'One row per commit that shipped a version, newest first; a blank cell means that plugin did\n' +
    'not move in that commit. A version links to its commit, or carries the short id where the\n' +
    'commit has not been pushed yet. Per-plugin notes are in each plugin\'s own `RELEASES.md`.\n\n' +
    PLUGINS.map((p) => '**' + short(p) + '** [' + p + '](' + p + '/RELEASES.md)').join(' · ') + '\n\n' +
    '| Date | ' + PLUGINS.map(short).join(' | ') + ' | Change |\n' +
    '| --- |' + PLUGINS.map(() => ' --- |').join('') + ' --- |\n' +
    rows.join('\n') + '\n';
}

const files = {};
const all = [];
PLUGINS.forEach((p) => {
  const rs = releasesFor(p);
  all.push(...rs);
  files[p + '/RELEASES.md'] = pluginFile(p, rs);
});
files['RELEASES.md'] = rootFile(all);

// --check compares the *releases*, not the bytes. Pushing a commit turns a short
// id into a link without any release having changed, and a check that failed on
// that would nag after every push - which is how a check gets switched off.
const structure = (text) => text.replace(/\]\(\S+\)/g, ']').replace(/\(`[0-9a-f]{7}`\)/g, '');

if (process.argv.indexOf('--check') !== -1) {
  const stale = Object.keys(files).filter((f) => {
    let cur = '';
    try { cur = fs.readFileSync(path.join(REPO, f), 'utf8'); } catch (e) { return true; }
    return structure(cur) !== structure(files[f]);
  });
  if (stale.length) {
    console.log(stale.join('\n'));
    process.exit(1);
  }
  process.exit(0);
}

Object.keys(files).forEach((f) => fs.writeFileSync(path.join(REPO, f), files[f]));
console.log('wrote ' + Object.keys(files).length + ' files, ' + all.length + ' releases');
